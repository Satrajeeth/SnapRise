    @staticmethod
    async def get_task(db: AsyncSession, task_id: UUID, include_linked_tasks: bool = False) -> Optional[Task]:
        from sqlalchemy.orm import selectinload
        from app.models.task_link import TaskLink
        
        options = [selectinload(Task.subtasks)]
        if include_linked_tasks:
            options.extend([
                selectinload(Task.source_links).selectinload(TaskLink.target_task),
                selectinload(Task.target_links).selectinload(TaskLink.source_task)
            ])
        else:
            options.extend([
                selectinload(Task.source_links),
                selectinload(Task.target_links)
            ])

        result = await db.execute(
            select(Task)
            .where(Task.id == task_id)
            .options(*options)
        )
        task = result.scalar_one_or_none()
        if task:
            # Fetch Board for encryption
            board_result = await db.execute(
                select(Board)
                .join(Column)
                .where(Column.id == task.column_id)
            )
            board = board_result.scalar()
            board_enc = board.encryption_status if board else EncryptionStatus.DISABLED
            security_manager.process_task_after_load(task, board_enc)
            
            # Combine links for the schema
            task.links = task.source_links + task.target_links
            
        return task
    
