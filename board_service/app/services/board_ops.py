    #Task Ops
    @staticmethod
    async def create_task(db: AsyncSession, task_in: TaskCreate) -> Task:
        #WIP - Work in progress  Limit Check 
        col = await db.get(Column, task_in.column_id)
        if col and col.wip_limit :
            from sqlalchemy import func
            count_result = await db.execute(
                select(func.count(Task.id)).where(Task.column_id == col.id)
            )
            current_count = count_result.scalar()
            if current_count >= col.wip_limit:
                raise HTTPException(
                    status_code=400, #Means Bad Request 
                    detail=f"Column '{col.name}' has reached its WIP limit of {col.wip_limit}."
                )
            '''It converts the Pydantic input (task_in) into a dictionary and uses it to create a 
            new Task object by unpacking its fields as arguments.
            model_dump() converts a Pydantic model instance into a Python dictionary of its data.'''
            task = Task(**task_in.model_dump())

            #Fetch Board for encryption and custom fields schema 
            result = await db.execute(
                select(Board)
                .join(Column)
                .where(Column.id == task_in.column_id)
            )
            '''scalar()- Returns the first column of the first row, or None if no result.
            scalar_one_or_none() - Returns one scalar value or None
            scalar_one() - Returns exactly one scalar value
            scalars() - Returns all scalar values as an iterable
            _source_supports_scalars - Internal flag (not for direct use) . Indicates whether the result supports scalar extraction'''
            board = result.scalar()
            board_enc = board.encryption_status if board else EncryptionStatus.DISABLED

            #Custom Fields Validation
            if board and "custom_fields_schema" in board.settings:
                from app.services.custom_fields_service import CustomFieldsService
                errors = CustomFieldsService.validate_custom_fields(
                    task.custom_fields,
                    board.settings["custom_fields_schema"]
                )
                if errors:
                    from fastapi import HTTPException
                    raise HTTPException(
                        status_code=400,
                        detail={"errors": errors}
                    )
                
            security_manager.process_task_for_storage(task, board_enc)
            db.add(task)
            await db.flush()
            security_manager.process_task_after_load(task, board_enc)
            return task
        
    @staticmethod
    async def update_task(db: AsyncSession, task_id: UUID, task_in: TaskUpdate) -> Optional[Task]:
        task = await db.get(Task, task_id)
        if not task:
            return None
        
        update_data = task_in.model_dump(exclude_unset=True)

        # Fetch Board for encryption and custom fields schema (always needed)
        result = await db.execute(
            select(Board)
            .join(Column)
            .where(Column.id == task.column_id)
        )
        board = result.scalar()
        board_enc = board.encryption_status if board else EncryptionStatus.DISABLED

        #WIP Limit Check
        old_col_id = task.column_id
        if "column_id" in update_data and update_data["column_id"] != old_col_id:
            new_col_id = update_data["column_id"]
            new_col = await db.get(Column, new_col_id)
            if new_col and new_col.wip_limit:
                from sqlalchemy import func
                count_result = await db.execute(
                    select(func.count(Task.id)).where(Task.column_id == new_col_id)
                )
                current_count = count_result.scalar()
                if current_count >= new_col.wip_limit:
                    raise HTTPException(
                        status_code=400,
                        detail=f"Column '{new_col.name}' has reached its WIP limit of {new_col.wip_limit}."
                    )
                
                #Trigger Automations
                from app.services.automation_service import AutomationService
                await AutomationService.process_task_move(db, task, old_col_id, new_col_id)

        #Custom Fields Validation
        if board and "custom_fields_schema" in board.settings:
            from app.services.custom_fields_service import CustomFieldsService
            current_fields = task.custom_fields.copy() if task.custom_fields else {}
            if "custom_fields" in update_data:
                current_fields.update(update_data["custom_fields"])

            errors = CustomFieldsService.validate_custom_fields(
                current_fields,
                board.settings["custom_fields_schema"]
            )

            if errors:
                raise HTTPException(
                    status_code=400,
                    detail={"errors": errors}
                )
            
        for key,value in update_data.items():
            setattr(task, key, value)

        security_manager.process_task_for_storage(task, board_enc)
        await db.flush()
        security_manager.process_task_after_load(task, board_enc)
        return task
    
